def executive_report(data: dict[str, Any], product: dict[str, Any]) -> Report:
    composite = data["composite"]
    scores = data["scores"]
    profile = data["profile"]
    recommendations = data["recommendations"]
    competitors = data["competitors"]

    lines = [
        f"# Executive Product Analysis: {product['name']}",
        "",
        f"_{product.get('one_liner', '')}_",
        "",
        f"**Product score: {composite['score']:.0f} / 100** "
        f"({composite['confidence']:.0%} average confidence, "
        f"{composite['coverage']:.0%} of the weighting model covered)",
        "",
    ]

    if profile:
        lines += [
            "## Summary",
            "",
            profile["summary"],
            "",
            f"**Primary problem solved:** {profile['primary_problem']}",
            "",
        ]

    if scores:
        lines += ["## Scores", "", "| Dimension | Score | Confidence | Rationale |", "|---|---|---|---|"]
        for score in scores:
            dimension = ScoreDimension(score["dimension"])
            lines.append(
                f"| {dimension.label}{' (inverted)' if score['inverted'] else ''} "
                f"| {score['score']:.0f} | {score['confidence']:.0%} "
                f"| {score['explanation'][:180].replace('|', '/')} |"
            )
        lines.append("")

    if competitors:
        lines += ["## Competitive set", "", "| Competitor | Type | Threat | Positioning |", "|---|---|---|---|"]
        for competitor in competitors[:15]:
            lines.append(
                f"| {competitor['name']} | {competitor['competitor_type']} "
                f"| {competitor['threat_level']} "
                f"| {competitor['positioning'][:120].replace('|', '/')} |"
            )
        lines.append("")

    if recommendations:
        lines += ["## Recommendations", ""]
        for rec in recommendations:
            lines += [
                f"### {rec['verdict'].replace('_', ' ').upper()}: {rec['title']}",
                "",
                f"**Problem:** {rec['problem']}",
                "",
                f"**Recommendation:** {rec['recommendation']}",
                "",
                f"**Why:** {rec['reason']}",
                "",
                f"_Effort {rec['effort'].upper()} · priority {rec['priority']} · "
                f"{rec['confidence']:.0%} confidence · decision: {rec['decision_state']}_",
                "",
            ]

    lines.append(_evidence_footer(data["quality"]))
    return Report(
        title=f"Executive Product Analysis: {product['name']}",
        markdown="\n".join(lines),
        filename=f"executive-analysis-{_slug(product['name'])}.md",
    )


def competitive_report(data: dict[str, Any], product: dict[str, Any]) -> Report:
    competitors = data["competitors"]
    lines = [f"# Competitive Intelligence Report: {product['name']}", ""]

    if not competitors:
        lines.append("_No competitors were identified in this analysis._")
    for competitor in competitors:
        lines += [
            f"## {competitor['name']}",
            "",
            f"- **Type:** {competitor['competitor_type']}",
            f"- **Threat level:** {competitor['threat_level']}",
            f"- **Website:** {competitor.get('website') or 'unknown'}",
            f"- **Target customer:** {competitor['target_customer']}",
            f"- **Positioning:** {competitor['positioning']}",
            f"- **Pricing:** {competitor['pricing_summary']}",
            f"- **Evidence grade:** {_GRADE_LABELS.get(competitor['grade'], competitor['grade'])} "
            f"({competitor['confidence']:.0%} confidence)",
            "",
            f"**Why a competitor:** {competitor['rationale']}",
            "",
            "**Strengths**",
            _bullets(competitor["strengths"]),
            "",
            "**Weaknesses**",
            _bullets(competitor["weaknesses"]),
            "",
            "**Known features**",
            _bullets(competitor["features"]),
            "",
        ]

    lines.append(_evidence_footer(data["quality"]))
    return Report(
        title=f"Competitive Intelligence: {product['name']}",
        markdown="\n".join(lines),
        filename=f"competitive-intelligence-{_slug(product['name'])}.md",
    )


def market_report(data: dict[str, Any], product: dict[str, Any]) -> Report:
    market = data["market"]
    lines = [f"# Market Analysis: {product['name']}", ""]

    if not market:
        lines.append("_No market analysis is available for this version._")
    else:
        lines += [
            f"**Market:** {market['market_definition']}",
            "",
            f"- Maturity: {market['maturity']}",
            f"- Competitive concentration: {market['competitive_concentration']}",
            "",
            "## Market sizing",
            "",
        ]
        for model in market["sizing"]:
            lines += [
                f"### {model['label']}: ${model['value_usd']:,.0f}",
                "",
                f"**Formula:** `{model['formula']}`",
                "",
                f"_Basis: {model['basis']} · {model['confidence']:.0%} confidence_",
                "",
                "**Variables**",
                _bullets(model["variables"]),
                "",
                "**Assumptions**",
                _bullets(model["assumptions"]),
                "",
            ]
        lines += [
            "## Entry barriers",
            _bullets(market["entry_barriers"]),
            "",
            "## Adjacent markets",
            _bullets(market["adjacent_markets"]),
            "",
        ]

    lines.append(_evidence_footer(data["quality"]))
    return Report(
        title=f"Market Analysis: {product['name']}",
        markdown="\n".join(lines),
        filename=f"market-analysis-{_slug(product['name'])}.md",
    )


def strategy_report(data: dict[str, Any], product: dict[str, Any]) -> Report:
    """Positioning, pricing, growth and GTM in one document."""
    lines = [f"# Strategy Report: {product['name']}", ""]

    positioning = data.get("positioning")
    if positioning:
        messaging = positioning.get("messaging", {})
        lines += [
            "## Positioning",
            "",
            f"**Recommended strategy: {positioning['recommended_strategy']}**",
            "",
            positioning["recommendation_reason"],
            "",
            f"**Positioning statement:** {messaging.get('positioning_statement', '')}",
            "",
            f"**Unique value proposition:** {messaging.get('unique_value_proposition', '')}",
            "",
            f"**Homepage headline:** {messaging.get('homepage_headline', '')}",
            "",
            f"**Subheadline:** {messaging.get('homepage_subheadline', '')}",
            "",
            f"**Elevator pitch:** {messaging.get('elevator_pitch', '')}",
            "",
            "### Options considered",
            "",
            "| Strategy | Fit | Target customer | Value proposition |",
            "|---|---|---|---|",
        ]
        for option in positioning["options"]:
            lines.append(
                f"| {option['strategy_name']} | {option['fit_score']:.0f} "
                f"| {option['target_customer'][:60].replace('|', '/')} "
                f"| {option['value_proposition'][:100].replace('|', '/')} |"
            )
        lines.append("")

    pricing = data.get("pricing")
    if pricing:
        lines += [
            "## Pricing",
            "",
            f"**Recommended model:** {pricing['recommended_model']}",
            "",
            f"**Value metric:** {pricing['value_metric']}",
            "",
            pricing["rationale"],
            "",
            "### Tiers",
            "",
            "| Tier | Price/mo | Segment | Limits |",
            "|---|---|---|---|",
        ]
        for tier in pricing["tiers"]:
            lines.append(
                f"| {tier['name']} | {format_price(tier['price_monthly_usd'])} "
                f"| {tier['target_segment'][:40].replace('|', '/')} "
                f"| {tier['limits'][:60].replace('|', '/')} |"
            )
        lines += ["", "### Assumptions", _bullets(pricing["assumptions"]), ""]

    growth = data.get("growth")
    if growth:
        lines += [
            "## Growth",
            "",
            f"**Primary motion:** {growth['primary_motion']}",
            "",
            growth["motion_rationale"],
            "",
            "### Channel priorities",
            "",
            "| Channel | Fit | Why | First experiment |",
            "|---|---|---|---|",
        ]
        for channel in growth["channels"]:
            lines.append(
                f"| {channel['channel']} | {channel['fit_score']:.0f} "
                f"| {channel['why_appropriate'][:110].replace('|', '/')} "
                f"| {channel['first_experiment'][:80].replace('|', '/')} |"
            )
        lines += [
            "",
            "### Sequencing",
            _bullets(growth["sequencing"]),
            "",
            "### Channels to avoid",
            _bullets(growth["channels_to_avoid"]),
            "",
        ]

    gtm = data.get("gtm")
    if gtm:
        lines += [
            "## Go-to-market",
            "",
            f"**Beachhead segment:** {gtm['target_segment']}",
            "",
            gtm["beachhead_rationale"],
            "",
            f"**Launch strategy:** {gtm['launch_strategy']}",
            "",
            "### Phases",
            "",
        ]
        for phase in gtm["phases"]:
            lines += [
                f"#### {phase['horizon'].replace('_', ' ').title()} "
                f"({phase['owner_role']})",
                "",
                "**Objectives**",
                _bullets(phase["objectives"]),
                "",
                "**Activities**",
                _bullets(phase["activities"]),
                "",
                "**Milestones**",
                _bullets(phase["milestones"]),
                "",
            ]
        lines += ["### Metrics", _bullets(gtm["metrics"]), "", "### Risks", _bullets(gtm["risks"]), ""]

    if len(lines) <= 2:
        lines.append("_No strategy analysis is available for this version._")

    lines.append(_evidence_footer(data["quality"]))
    return Report(
        title=f"Strategy Report: {product['name']}",
        markdown="\n".join(lines),
        filename=f"strategy-{_slug(product['name'])}.md",
    )


def evidence_report(data: dict[str, Any], product: dict[str, Any], evidence: list[dict]) -> Report:
    lines = [
        f"# Evidence Ledger: {product['name']}",
        "",
        "Every claim underpinning this analysis, with its grade, confidence and sources.",
        "",
    ]
    by_grade: dict[str, list[dict]] = {}
    for item in evidence:
        by_grade.setdefault(item["grade"], []).append(item)

    for grade in [
        "verified_fact",
        "strong_inference",
        "user_supplied",
        "weak_inference",
        "ai_hypothesis",
    ]:
        items = by_grade.get(grade, [])
        if not items:
            continue
        lines += [f"## {_GRADE_LABELS[grade]} ({len(items)})", ""]
        for item in items:
            sources = ", ".join(
                c.get("url") or c.get("title", "") for c in item.get("citations", [])
            )
            lines.append(
                f"- **{item['claim']}** — {item['confidence']:.0%} confidence, "
                f"agent `{item['agent']}`"
                + (f"  \n  Sources: {sources}" if sources else "  \n  _No source_")
            )
        lines.append("")

    lines.append(_evidence_footer(data["quality"]))
    return Report(
        title=f"Evidence Ledger: {product['name']}",
        markdown="\n".join(lines),
        filename=f"evidence-ledger-{_slug(product['name'])}.md",
    )


