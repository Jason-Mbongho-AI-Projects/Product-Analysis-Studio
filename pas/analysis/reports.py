def markdown_to_html(markdown: str, title: str) -> str:
    """Render report markdown as a self-contained, printable HTML document.

    A minimal converter rather than a dependency: reports emit a known subset of
    markdown (headings, tables, bullets, bold, code spans). Every value is
    escaped before interpolation.
    """
    html_lines: list[str] = []
    in_table = False
    in_list = False

    def close_blocks() -> None:
        nonlocal in_table, in_list
        if in_table:
            html_lines.append("</tbody></table>")
            in_table = False
        if in_list:
            html_lines.append("</ul>")
            in_list = False

    def inline(text: str) -> str:
        safe = escape(text)
        # Bold and code only; applied after escaping so markup cannot be injected.
        while "**" in safe:
            safe = safe.replace("**", "<strong>", 1)
            if "**" in safe:
                safe = safe.replace("**", "</strong>", 1)
            else:
                safe += "</strong>"
        while safe.count("`") >= 2:
            safe = safe.replace("`", "<code>", 1).replace("`", "</code>", 1)
        return safe

    for raw in markdown.split("\n"):
        line = raw.rstrip()

        if not line:
            close_blocks()
            continue

        if line.startswith("|"):
            cells = [c.strip() for c in line.strip("|").split("|")]
            if all(set(c) <= {"-", ":", " "} and c for c in cells):
                continue  # separator row
            if not in_table:
                close_blocks()
                html_lines.append("<table><thead><tr>")
                html_lines += [f"<th>{inline(c)}</th>" for c in cells]
                html_lines.append("</tr></thead><tbody>")
                in_table = True
            else:
                html_lines.append("<tr>" + "".join(f"<td>{inline(c)}</td>" for c in cells) + "</tr>")
            continue

        if line.startswith("- "):
            if not in_list:
                close_blocks()
                html_lines.append("<ul>")
                in_list = True
            html_lines.append(f"<li>{inline(line[2:])}</li>")
            continue

        close_blocks()

        if line.startswith("#"):
            level = min(len(line) - len(line.lstrip("#")), 6)
            html_lines.append(f"<h{level}>{inline(line.lstrip('# '))}</h{level}>")
        elif line.startswith("---"):
            html_lines.append("<hr>")
        elif line.startswith("_") and line.endswith("_") and len(line) > 2:
            html_lines.append(f"<p><em>{inline(line[1:-1])}</em></p>")
        else:
            html_lines.append(f"<p>{inline(line)}</p>")

    close_blocks()
    body = "\n".join(html_lines)

    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{escape(title)}</title>
<style>
  body {{ font-family: -apple-system, "Segoe UI", Roboto, sans-serif; line-height: 1.6;
         max-width: 900px; margin: 2.5rem auto; padding: 0 1.25rem; color: #1a202c; }}
  h1 {{ font-size: 1.9rem; border-bottom: 2px solid #e2e8f0; padding-bottom: .5rem; }}
  h2 {{ font-size: 1.35rem; margin-top: 2rem; color: #2d3748; }}
  h3 {{ font-size: 1.1rem; margin-top: 1.4rem; }}
  table {{ border-collapse: collapse; width: 100%; margin: 1rem 0; font-size: .9rem; }}
  th, td {{ border: 1px solid #e2e8f0; padding: .5rem .65rem; text-align: left;
            vertical-align: top; }}
  th {{ background: #f7fafc; font-weight: 600; }}
  code {{ background: #edf2f7; padding: .12rem .35rem; border-radius: 3px;
          font-size: .88em; }}
  hr {{ border: none; border-top: 1px solid #e2e8f0; margin: 2rem 0; }}
  em {{ color: #4a5568; }}
  @media print {{ body {{ margin: 0; max-width: none; }} }}
</style></head>
<body>
{body}
</body></html>"""


def scores_csv(scores: list[dict[str, Any]]) -> str:
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(
        ["Dimension", "Score", "Inverted", "Weight", "Confidence", "Explanation", "Assumptions"]
    )
    for score in scores:
        writer.writerow(
            [
                ScoreDimension(score["dimension"]).label,
                f"{score['score']:.1f}",
                "yes" if score["inverted"] else "no",
                f"{score['weight']:.3f}",
                f"{score['confidence']:.2f}",
                score["explanation"],
                " | ".join(score.get("assumptions", [])),
            ]
        )
    return buffer.getvalue()


def competitors_csv(competitors: list[dict[str, Any]]) -> str:
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(
        ["Name", "Company", "Type", "Threat", "Website", "Target customer",
         "Positioning", "Pricing", "Grade", "Confidence", "Strengths", "Weaknesses", "Features"]
    )
    for competitor in competitors:
        writer.writerow(
            [
                competitor["name"],
                competitor["company"],
                competitor["competitor_type"],
                competitor["threat_level"],
                competitor.get("website") or "",
                competitor["target_customer"],
                competitor["positioning"],
                competitor["pricing_summary"],
                competitor["grade"],
                f"{competitor['confidence']:.2f}",
                " | ".join(competitor["strengths"]),
                " | ".join(competitor["weaknesses"]),
                " | ".join(competitor["features"]),
            ]
        )
    return buffer.getvalue()


def evidence_csv(evidence: list[dict[str, Any]]) -> str:
    buffer = io.StringIO()
    writer = csv.writer(buffer, lineterminator="\n")
    writer.writerow(["Claim", "Detail", "Grade", "Confidence", "Agent", "Subject", "Sources", "Recorded"])
    for item in evidence:
        writer.writerow(
            [
                item["claim"],
                item.get("detail", ""),
                item["grade"],
                f"{item['confidence']:.2f}",
                item["agent"],
                item.get("subject_type", ""),
                " | ".join(c.get("url") or c.get("title", "") for c in item.get("citations", [])),
                item["created_at"],
            ]
        )
    return buffer.getvalue()


def full_export_json(data: dict[str, Any], product: dict[str, Any], evidence: list[dict]) -> str:
    """Complete structured export of one analysis (spec 56)."""
    payload = {
        "exported_at": _stamp(),
        "generator": "Product Analysis Studio",
        "product": {
            key: product.get(key)
            for key in (
                "id", "name", "one_liner", "category", "subcategory", "industry",
                "business_model", "market_segment", "maturity", "source_url",
            )
        },
        "analysis": data.get("analysis"),
        "composite_score": data.get("composite"),
        "scores": data.get("scores"),
        "profile": data.get("profile"),
        "competitors": data.get("competitors"),
        "market": data.get("market"),
        "customers": data.get("customers"),
        "recommendations": data.get("recommendations"),
        "positioning": data.get("positioning"),
        "pricing": data.get("pricing"),
        "growth": data.get("growth"),
        "gtm": data.get("gtm"),
        "evidence": evidence,
        "sources": data.get("sources"),
        "evidence_quality": data.get("quality"),
    }
    return json.dumps(payload, indent=2, default=str)
