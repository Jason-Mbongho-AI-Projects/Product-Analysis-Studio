def format_price(value: float | None, suffix: str = "") -> str:
    """Render a price, honouring the free (0) and custom (-1) sentinels."""
    if value is None:
        return "Unknown"
    if value < 0:
        return "Custom"
    if value == 0:
        return "Free"
    return f"${value:,.0f}{suffix}"


_GRADE_LABELS = {
    "verified_fact": "Verified fact",
    "strong_inference": "Strong inference",
    "weak_inference": "Weak inference",
    "ai_hypothesis": "AI hypothesis",
    "user_supplied": "User supplied",
}


@dataclass
class Report:
    title: str
    markdown: str
    filename: str

    def as_html(self) -> str:
        return markdown_to_html(self.markdown, self.title)


def _stamp() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")


def _slug(text: str) -> str:
    keep = [c.lower() if c.isalnum() else "-" for c in text]
    return "".join(keep).strip("-").replace("--", "-")[:60] or "report"


def _bullets(items: list[Any], empty: str = "_None recorded._") -> str:
    if not items:
        return empty
    return "\n".join(f"- {item}" for item in items)


def _evidence_footer(quality: dict[str, Any]) -> str:
    """Every report states its own evidence basis. Non-negotiable."""
    total = quality.get("total", 0)
    ratio = quality.get("evidence_backed_ratio", 0.0)
    sources = quality.get("distinct_sources", 0)

    if total == 0:
        basis = "No evidence records were produced for this analysis."
    elif sources == 0:
        basis = (
            f"**No external sources were retrieved.** All {total} claims derive from "
            "model knowledge and are hypotheses, not verified facts."
        )
    else:
        basis = (
            f"{total} claims recorded, {ratio:.0%} backed by a retrieved source, "
            f"across {sources} distinct sources."
        )

    return (
        "\n\n---\n\n## Evidence basis\n\n"
        f"{basis}\n\n"
        "Claims in this report are graded. AI-inferred findings are labelled as such "
        "and should be validated before acting on them. Market sizing figures are "
        "derived estimates showing their formulas, not measured market data.\n\n"
        f"_Generated by Product Analysis Studio on {_stamp()}._\n"
    )


