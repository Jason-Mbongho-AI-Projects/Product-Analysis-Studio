"""Report Studio (spec 30 / 56).

Reports are built from stored intelligence, never regenerated by a model, so a
downloaded report always matches what the UI showed and costs nothing to
produce.

Formats are chosen for what is achievable without heavyweight dependencies:
Markdown and HTML (print-to-PDF from the browser), plus CSV and JSON for
structured data. HTML is escaped at every interpolation - report content
includes model output and fetched page titles.
"""

